func TestPrintLifecycle(t *testing.T) {
	a := newApp(t, noPoll)
	a.ok(a.alice, "PUT", "/api/v1/settings", map[string]any{"currency": "EUR", "kwh_price": 0.5})
	p := obj2(a.ok(a.alice, "POST", "/api/v1/printers", map[string]any{"name": "Mk4", "watts": 200, "wear_per_hour": 100}), "printer")
	sp := obj2(a.ok(a.alice, "POST", "/api/v1/spools", map[string]any{"filament": map[string]any{"material": "PETG", "name": "Black", "net_weight": 1000, "price": 2000}}), "spool")
	a.ok(a.alice, "PUT", "/api/v1/printers/"+id(p)+"/spool", map[string]any{"spool_id": num(sp, "id")})
	m, file := a.uploadModel(a.alice, "cube_PETG.gcode", []byte(testGcode), nil)
	if num(file, "est_seconds") != 3723 || num(file, "est_grams") != 12 || str(file, "material") != "PETG" {
		t.Fatalf("G-code not read: %v", file)
	}
	set := obj2(file, "settings")
	if str(set, "infill") != "15%" || str(set, "walls") != "3" || str(set, "supports") != "no" {
		t.Fatalf("settings not read: %v", set)
	}
	j := a.ok(a.alice, "POST", "/api/v1/jobs", map[string]any{"model_id": num(m, "id"), "quantity": 2})
	if num(j, "file_id") != num(file, "id") {
		t.Fatalf("the job takes the model's G-code: %v", j)
	}
	pr := a.ok(a.alice, "POST", "/api/v1/jobs/"+id(j)+"/start", map[string]any{"printer_id": num(p, "id")})
	if str(pr, "status") != "printing" || num(pr, "spool_id") != num(sp, "id") {
		t.Fatalf("start: %v", pr)
	}
	// a second start on the same printer is refused
	a.expect(400, a.alice, "POST", "/api/v1/jobs/"+id(j)+"/start", map[string]any{"printer_id": num(p, "id")})
	done := a.ok(a.alice, "POST", "/api/v1/prints/"+id(pr)+"/finish", map[string]any{"status": "done", "seconds": 3600, "rating": 4})
	if num(done, "grams") != 12 {
		t.Fatalf("grams: %v", done)
	}
	// filament 12 g of a 20.00 spool = 0.24; power 200 W × 1 h × 0.50 = 0.10; wear 1.00
	if num(done, "filament_cost") != 24 || num(done, "power_cost") != 10 || num(done, "wear_cost") != 100 {
		t.Fatalf("costs: %v", done)
	}
	s2 := obj2(a.ok(a.alice, "GET", "/api/v1/spools/"+id(sp), nil), "spool")
	if num(s2, "left_g") != 988 {
		t.Fatalf("the spool should have 988 g left: %v", s2)
	}
	j2 := obj2(a.ok(a.alice, "GET", "/api/v1/jobs/"+id(j), nil), "job")
	if num(j2, "done_count") != 1 || str(j2, "status") != "queued" {
		t.Fatalf("job after one: %v", j2)
	}
	// the bed must be cleared first
	a.expect(400, a.alice, "POST", "/api/v1/jobs/"+id(j)+"/start", map[string]any{"printer_id": num(p, "id")})
	a.ok(a.alice, "POST", "/api/v1/printers/"+id(p)+"/control", map[string]any{"action": "clear"})
	pr2 := a.ok(a.alice, "POST", "/api/v1/jobs/"+id(j)+"/start", map[string]any{"printer_id": num(p, "id")})
	failed := a.ok(a.alice, "POST", "/api/v1/prints/"+id(pr2)+"/finish", map[string]any{"status": "failed", "fail_reason": "adhesion", "grams": 3})
	if str(failed, "fail_reason") != "adhesion" {
		t.Fatalf("failed: %v", failed)
	}
	// editing the grams moves them on the spool; deleting gives them back
	a.ok(a.alice, "PUT", "/api/v1/prints/"+id(failed), map[string]any{"grams": 5})
	if left := num(obj2(a.ok(a.alice, "GET", "/api/v1/spools/"+id(sp), nil), "spool"), "left_g"); left != 983 {
		t.Fatalf("after the edit: %v", left)
	}
	a.expect(204, a.alice, "DELETE", "/api/v1/prints/"+id(failed), nil)
	if left := num(obj2(a.ok(a.alice, "GET", "/api/v1/spools/"+id(sp), nil), "spool"), "left_g"); left != 988 {
		t.Fatalf("after the delete: %v", left)
	}
	// weighing: 600 g left
	a.ok(a.alice, "POST", "/api/v1/spools/"+id(sp)+"/weigh", map[string]any{"left_g": 600})
	if left := num(obj2(a.ok(a.alice, "GET", "/api/v1/spools/"+id(sp), nil), "spool"), "left_g"); left != 600 {
		t.Fatalf("after weighing: %v", left)
	}
	// stats and the day
	st := a.ok(a.alice, "GET", "/api/v1/stats", nil)
	if num(obj2(st, "total"), "done") != 1 {
		t.Fatalf("stats: %v", st["total"])
	}
	day := a.ok(a.alice, "GET", "/api/v1/day/"+today(), nil)
	if len(day["items"].([]any)) == 0 {
		t.Fatal("the day is empty")
	}
}

