	j := a.ok(a.alice, "POST", "/api/v1/jobs", map[string]any{"model_id": num(m, "id")})
	// starting sends the G-code, the printer starts it
	pr := a.ok(a.alice, "POST", "/api/v1/jobs/"+id(j)+"/start", map[string]any{"printer_id": num(p, "id")})
	if fp.uploaded != "cube.gcode" || fp.state != "printing" {
		t.Fatalf("the printer got %q (%s)", fp.uploaded, fp.state)
	}
	printer, _ := a.st.GetPrinter(ctx, a.ids["Alice"], int64(num(p, "id")))
	fp.set("printing", "cube.gcode", 0.5)
	a.s.pollOne(ctx, printer)
