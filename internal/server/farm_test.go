func noPoll(c *config.Config) { c.PollSeconds = 0 }

func obj2(m map[string]any, k string) map[string]any { v, _ := m[k].(map[string]any); return v }

// uploadModel sends a file as a form and returns the first model and file.
func (a *app) uploadModel(auth, name string, data []byte, fields map[string]string) (map[string]any, map[string]any) {
	a.t.Helper()
	var b bytes.Buffer
	mw := multipart.NewWriter(&b)
	for k, v := range fields {
		_ = mw.WriteField(k, v)
	}
	fw, _ := mw.CreateFormFile("file", name)
	_, _ = fw.Write(data)
	_ = mw.Close()
	req, _ := http.NewRequest("POST", a.url+"/api/v1/models/upload", &b)
	req.Header.Set("Content-Type", mw.FormDataContentType())
	req.Header.Set("Authorization", "Bearer "+auth)
	res, err := http.DefaultClient.Do(req)
	if err != nil {
		a.t.Fatal(err)
	}
	defer res.Body.Close()
	raw, _ := io.ReadAll(res.Body)
	if res.StatusCode != 201 {
		a.t.Fatalf("upload %s → %d %s", name, res.StatusCode, raw)
	}
	var out struct {
		Added []struct {
			Model map[string]any `json:"model"`
			File  map[string]any `json:"file"`
		} `json:"added"`
	}
	_ = json.Unmarshal(raw, &out)
	return out.Added[0].Model, out.Added[0].File
}

