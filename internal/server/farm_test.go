// fakePrinter is a printer on the network that prints a file and finishes.
type fakePrinter struct {
	mu       sync.Mutex
	state    string
	file     string
	progress float64
	uploaded string
	key      string
}

func (f *fakePrinter) set(state, file string, progress float64) {
	f.mu.Lock()
	f.state, f.file, f.progress = state, file, progress
	f.mu.Unlock()
}

func (f *fakePrinter) moonraker() http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		f.mu.Lock()
		defer f.mu.Unlock()
		switch {
		case r.URL.Path == "/printer/objects/query":
			fmt.Fprintf(w, `{"result":{"status":{"print_stats":{"state":%q,"filename":%q,"print_duration":600,"filament_used":1000},"virtual_sdcard":{"progress":%v},"extruder":{"temperature":215,"target":215},"heater_bed":{"temperature":60,"target":60},"webhooks":{"state":"ready"}}}}`, f.state, f.file, f.progress)
		case r.URL.Path == "/server/files/upload":
			_ = r.ParseMultipartForm(1 << 20)
			fh := r.MultipartForm.File["file"][0]
			f.uploaded = fh.Filename
			if r.FormValue("print") == "true" {
				f.state, f.file, f.progress = "printing", fh.Filename, 0.01
			}
			fmt.Fprint(w, `{"result":"ok"}`)
		case r.URL.Path == "/printer/print/pause":
			f.state = "paused"
			fmt.Fprint(w, `{"result":"ok"}`)
		default:
			http.NotFound(w, r)
		}
	})
}

func (f *fakePrinter) octoprint() http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		if r.Header.Get("X-Api-Key") != f.key {
			http.Error(w, "nope", 403)
			return
		}
		f.mu.Lock()
		defer f.mu.Unlock()
		switch r.URL.Path {
		case "/api/job":
			st := map[string]string{"printing": "Printing", "idle": "Operational", "complete": "Operational"}[f.state]
			fmt.Fprintf(w, `{"state":%q,"job":{"file":{"name":%q}},"progress":{"completion":%v,"printTime":300,"printTimeLeft":300}}`, st, f.file, f.progress*100)
		case "/api/printer":
			fmt.Fprint(w, `{"temperature":{"tool0":{"actual":200,"target":200},"bed":{"actual":55,"target":55}}}`)
		default:
			http.NotFound(w, r)
		}
	})
}

